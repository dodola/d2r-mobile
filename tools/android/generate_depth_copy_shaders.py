"""Reproduce the built-in Vulkan 1.1 depth-copy SPIR-V using NDK 27.2 glslc.

The application needs no runtime GLSL compiler. --check verifies the checked-in
header byte for byte. --glslc can select a compiler on another development host.
"""
import argparse
import os
from pathlib import Path
import struct
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--glslc', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    repo = Path(__file__).resolve().parents[2]
    compiler = args.glslc or (Path(os.environ['LOCALAPPDATA']) /
        'Android/Sdk/ndk/27.2.12479018/shader-tools/windows-x86_64/glslc.exe')
    root = repo / 'dm/gfx/nvn'
    output = ['/* Generated by tools/android/generate_depth_copy_shaders.py; do not edit. */']
    with tempfile.TemporaryDirectory(prefix='depth-copy-shaders-') as temp:
        for name in ('depth_copy.vert', 'depth_copy.frag', 'stencil_copy.frag'):
            binary = Path(temp) / (name + '.spv')
            subprocess.run([str(compiler), '--target-env=vulkan1.1', '-O',
                            str(root / 'shaders' / name), '-o', str(binary)], check=True)
            validator = compiler.with_name('spirv-val.exe' if compiler.suffix == '.exe' else 'spirv-val')
            subprocess.run([str(validator), '--target-env', 'vulkan1.1', str(binary)], check=True)
            data = binary.read_bytes()
            words = struct.unpack('<' + str(len(data) // 4) + 'I', data)
            output.append('static const uint32_t ' + name.replace('.', '_') + '_spv[] = {')
            for offset in range(0, len(words), 8):
                output.append('    ' + ','.join(f'0x{w:08x}' for w in words[offset:offset+8]) + ',')
            output.append('};')
    generated = '\n'.join(output) + '\n'
    header = root / 'nvn_vk_depth_copy_spv.inc'
    if args.check:
        if header.read_text(encoding='utf-8') != generated:
            raise RuntimeError('Depth copy SPIR-V differs; regenerate with the pinned compiler')
    else:
        header.write_text(generated, encoding='utf-8', newline='\n')
    print('Depth copy shaders ' + ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
